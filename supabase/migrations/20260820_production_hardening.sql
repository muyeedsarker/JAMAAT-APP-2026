-- Push configuration is stored in Vault under these names:
-- jamaat_vapid_private_key
-- jamaat_push_webhook_secret
create or replace function public.get_push_config(p_secret text)
returns table(private_key text)
language plpgsql security definer set search_path = public, vault
as $$
begin
  if p_secret is null then return; end if;
  if not exists (select 1 from vault.decrypted_secrets where name='jamaat_push_webhook_secret' and decrypted_secret=p_secret) then return; end if;
  return query select decrypted_secret from vault.decrypted_secrets where name='jamaat_vapid_private_key' limit 1;
end;
$$;
revoke all on function public.get_push_config(text) from public;

create or replace function public.notify_new_published_ward_item()
returns trigger language plpgsql security definer set search_path = public, vault, net
as $$
declare secret text; private_key text;
begin
  if new.status <> 'published' or old.status = 'published' then return new; end if;
  select decrypted_secret into secret from vault.decrypted_secrets where name='jamaat_push_webhook_secret' limit 1;
  select decrypted_secret into private_key from vault.decrypted_secrets where name='jamaat_vapid_private_key' limit 1;
  if secret is null or private_key is null then return new; end if;
  perform net.http_post(
    url := 'https://pgwxfccpphjjveoeeqhv.supabase.co/functions/v1/send-push-v2',
    headers := jsonb_build_object('Content-Type','application/json','x-jamaat-push-secret',secret),
    body := jsonb_build_object('privateKey',private_key,'title',case when new.type='Notice' then '📢 নতুন নোটিশ' else '📰 নতুন নিউজ' end,'message',new.title,'url','./news.html' || case when new.type='Notice' then '#notice' else '' end,'tag','ward-' || new.type)
  );
  return new;
end;
$$;
revoke all on function public.notify_new_published_ward_item() from public;
drop trigger if exists ward_item_push_notification on public.ward_items;
create trigger ward_item_push_notification after update of status on public.ward_items for each row execute function public.notify_new_published_ward_item();
