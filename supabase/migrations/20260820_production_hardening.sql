-- Production hardening for JAMAAT APP 2026.
-- Secret values are intentionally NOT stored in Git. Production keeps them in Supabase Vault.

create extension if not exists pg_net;

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists push_subscriptions_user_id_idx on public.push_subscriptions(user_id);
alter table public.push_subscriptions enable row level security;
drop policy if exists push_users_read_own on public.push_subscriptions;
create policy push_users_read_own on public.push_subscriptions for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists push_users_insert_own on public.push_subscriptions;
create policy push_users_insert_own on public.push_subscriptions for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists push_anon_insert on public.push_subscriptions;
create policy push_anon_insert on public.push_subscriptions for insert to anon with check (user_id is null);
drop policy if exists push_users_update_own on public.push_subscriptions;
create policy push_users_update_own on public.push_subscriptions for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists push_users_delete_own on public.push_subscriptions;
create policy push_users_delete_own on public.push_subscriptions for delete to authenticated using (user_id = (select auth.uid()));

