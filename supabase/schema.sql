-- Admin policies use a SECURITY DEFINER helper to avoid recursive RLS checks.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

drop policy if exists "admins_read_all" on public.ward_items;
create policy "admins_read_all"
  on public.ward_items for select
  to authenticated
  using (public.is_admin());

drop policy if exists "admins_update_items" on public.ward_items;
create policy "admins_update_items"
  on public.ward_items for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "admins_delete_items" on public.ward_items;
create policy "admins_delete_items"
  on public.ward_items for delete
  to authenticated
  using (public.is_admin());
